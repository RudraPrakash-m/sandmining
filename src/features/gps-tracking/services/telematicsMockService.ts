export class TelematicsDataService {
  static getAllVehicles(): TelematicsVehicle[] {
    return MOCK_TELEMATICS_VEHICLES;
  }

  static getVehicleById(id: string): TelematicsVehicle | undefined {
    return MOCK_TELEMATICS_VEHICLES.find(
      (v) => v.id === id || v.vehicleNumber.toLowerCase() === id.toLowerCase() || v.orderId === id
    );
  }

  static getTripsByCategory(category: TripCategory): TelematicsVehicle[] {
    return MOCK_TELEMATICS_VEHICLES.filter((v) => v.tripCategory === category);
  }

  static getTripByOrderId(orderId: string): TelematicsVehicle | undefined {
    return MOCK_TELEMATICS_VEHICLES.find(
      (v) => v.orderId?.toLowerCase() === orderId.toLowerCase() || v.bookingId?.toLowerCase() === orderId.toLowerCase()
    );
  }

  static getAlerts(): TelematicsAlert[] {
    return MOCK_TELEMATICS_ALERTS;
  }

  static getKpiCounts() {
    const all = MOCK_TELEMATICS_VEHICLES;
    return {
      total: all.length,
      active: all.filter((v) => v.tripCategory === "Active").length,
      inTransit: all.filter((v) => v.status === "In Transit" || v.status === "Near Destination").length,
      idle: all.filter((v) => v.status === "Idle").length,
      exception: all.filter((v) => v.status === "Exception").length,
      completed: all.filter((v) => v.tripCategory === "Completed").length,
      cancelled: all.filter((v) => v.tripCategory === "Cancelled").length,
    };
  }
}

