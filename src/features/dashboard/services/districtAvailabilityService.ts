/**
 * Service helpers for spatial analysis
 */
export const DistrictAvailabilityService = {
  getAllDistricts(): DistrictAvailabilityData[] {
    return CHHATTISGARH_DISTRICT_INVENTORY;
  },

  getDistrictById(id: string): DistrictAvailabilityData | undefined {
    return CHHATTISGARH_DISTRICT_INVENTORY.find((d) => d.id === id);
  },

  getDistrictBySvgPath(pathId: string): DistrictAvailabilityData | undefined {
    return CHHATTISGARH_DISTRICT_INVENTORY.find((d) => d.svgPathId === pathId);
  },

  getDistrictsByBasin(basin: RiverBasin): DistrictAvailabilityData[] {
    if (basin === "All Basins") return CHHATTISGARH_DISTRICT_INVENTORY;
    return CHHATTISGARH_DISTRICT_INVENTORY.filter((d) => d.riverBasin === basin);
  },

  getInventorySummary(data: DistrictAvailabilityData[] = CHHATTISGARH_DISTRICT_INVENTORY) {
    const totalDistricts = data.length;
    const totalAvailableQuantityMt = data.reduce((sum, d) => sum + d.availableQuantityMt, 0);
    const totalActiveSources = data.reduce((sum, d) => sum + d.activeSources, 0);
    const totalDailyDispatchMt = data.reduce((sum, d) => sum + d.dailyDispatchMt, 0);
    const avgCompliance =
      data.reduce((sum, d) => sum + d.complianceRatePct, 0) / (totalDistricts || 1);

    const levelCounts: Record<SandAvailabilityLevel, number> = {
      VERY_HIGH: 0,
      HIGH: 0,
      MODERATE: 0,
      LOW: 0,
      VERY_LOW: 0,
    };

    data.forEach((d) => {
      levelCounts[d.availabilityLevel] = (levelCounts[d.availabilityLevel] || 0) + 1;
    });

    return {
      totalDistricts,
      totalAvailableQuantityMt,
      totalActiveSources,
      totalDailyDispatchMt,
      avgCompliance: Number(avgCompliance.toFixed(1)),
      levelCounts,
    };
  },
};
